    /// `shortDescr` is a nullable field in core: an empty string is always written back as nil, so as not to keep an empty string pretending there is a description.
    private var shortDescrBinding: Binding<String> {
        Binding(
            get: { profile.shortDescr ?? "" },
            set: { value in
                profile.shortDescr = value.trimmingCharacters(in: .whitespaces).isEmpty ? nil : value
            }
        )
    }

    /// The moment of "core would rewrite it, but it has not been fixed yet". The criterion is the same sentence as the old page :170-171.
    private var nameNeedsFix: Bool {
        let name = profile.displayName.trimmingCharacters(in: .whitespaces)
        return !name.isEmpty && name != mkValidName(name)
    }

