struct PopopxCreateGroupView: View {
    @EnvironmentObject private var m: ChatModel
    @AppStorage(GROUP_DEFAULT_INCOGNITO, store: groupDefaults) private var incognitoDefault = false

    /// Both must be non-nil to reach the second stage; the condition is the same as the old page :32.
    @State private var chat: Chat?
    @State private var groupInfo: GroupInfo?
    @State private var profile = GroupProfile(displayName: "", fullName: "")

    /// This page's picker result and roles; the defaults come from the same source as that page (AddGroupMembersView.swift:33 `.member`).
    @State private var selectedContacts: Set<Int64> = []
    @State private var selectedRole: GroupMemberRole = .member

    /// The pair of states that `GroupLinkView` reads and writes itself on the incognito branch; the same pair as the old page :28-29.
    @State private var groupLink: GroupLink?
    @State private var groupLinkMemberRole: GroupMemberRole = .member

    var body: some View {
        if let chat, let groupInfo {
            secondStage(chat: chat, groupInfo: groupInfo)
        } else {
            PopopxCreateGroupForm(
                profile: $profile,
                incognito: $incognitoDefault,
                historyEnabled: historyBinding,
                selectedContacts: $selectedContacts,
                selectedRole: $selectedRole,
                currentIdentityName: currentIdentityName,
                contacts: invitableContacts,
                onSubmit: { await createGroup() }
            )
        }
    }

    // MARK: Second stage (the old page body's two branches and that one wrap-up, copied verbatim)

    /// Incognito = the existing group-link page; not incognito = the existing invite-members page.
    /// "People were already picked on this page" never reaches here at all — `createGroup()` goes straight to the wrap-up statement.
    @ViewBuilder private func secondStage(chat: Chat, groupInfo: GroupInfo) -> some View {
        if groupInfo.membership.memberIncognito {
            GroupLinkView(
                groupId: groupInfo.groupId,
                groupLink: $groupLink,
                groupLinkMemberRole: $groupLinkMemberRole,
                showTitle: false,
                creatingGroup: true
            ) {
                finishCreating(groupInfo)
            }
            .navigationTitle(Copy.linkStageTitle)
        } else {
            AddGroupMembersViewCommon(
                chat: chat,
                groupInfo: groupInfo,
                creatingGroup: true,
                showFooterCounter: false
            ) { _ in
                finishCreating(groupInfo)
            }
            .navigationBarTitleDisplayMode(.inline)
        }
    }

    /// The wrap-up of the old page :40-45 / :55-60, not one word changed: 0.5 second delay → dismiss all sheets → open this group.
    @MainActor private func finishCreating(_ groupInfo: GroupInfo) {
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
            dismissAllSheets(animated: true) {
                ItemsModel.shared.loadOpenChat(groupInfo.id)
            }
        }
    }

    // MARK: Data sources

    /// The current identity name used by the "who will this be shared with" line; same rule as the old page :191; an empty nickname is not guessed but falls straight to "Unnamed identity".
    private var currentIdentityName: String {
        let name = m.currentUser?.displayName.trimmingCharacters(in: .whitespaces) ?? ""
        return name.isEmpty ? Copy.unnamedIdentity : name
    }

    /// The current value of the history-messages item. While `groupPreferences` is still nil it is the default the old page hard-coded: on.
    private var historyEnabled: Bool {
        profile.groupPreferences?.history?.on ?? true
    }

    /// Writes back to `GroupProfile.groupPreferences.history` — this is a field core already knows, not a private boolean on the page
    /// （POPOPXChat/ChatTypes.swift:1851、:1916）。
    private var historyBinding: Binding<Bool> {
        Binding(
            get: { historyEnabled },
            set: { on in
                profile.groupPreferences = GroupPreferences(history: GroupPreference(enable: on ? .on : .off))
            }
        )
    }

    /// The roster = the same `filterMembersToAdd` as that page (Shared/Model/POPOPXAPI.swift:2093).
    /// The criterion `!incognitoDefault && contact.contactConnIncognito` is the pre-creation spelling of that sentence at AddGroupMembersView.swift:196
    /// `!chat.chatInfo.incognito && contact.contactConnIncognito`: `ChatInfo.incognito`
    /// for a group is `groupInfo.membership.memberIncognito` (POPOPXChat/ChatTypes.swift:2266), and that is exactly what
    /// this toggle decides, so while the group is not built yet the toggle is the truth value of that cell.
    private var invitableContacts: [PopopxInvitableContact] {
        filterMembersToAdd(m.groupMembers).map { contact in
            PopopxInvitableContact(
                id: contact.apiId,
                name: contact.displayName,
                imageStr: contact.image,
                inviteProhibited: !incognitoDefault && contact.contactConnIncognito
            )
        }
    }

    // MARK: Actions

    /// The four steps of the old page's `createGroup()` (:199-224) are kept as they are, then this page's own invitation shortcut follows.
    @MainActor private func createGroup() async {
        let created: GroupInfo
        do {
            profile.displayName = profile.displayName.trimmingCharacters(in: .whitespaces)
            profile.groupPreferences = GroupPreferences(history: GroupPreference(enable: historyEnabled ? .on : .off))
            let gInfo = try apiNewGroup(incognito: incognitoDefault, groupProfile: profile)
            Task {
                await m.loadGroupMembers(gInfo)
            }
            let c = Chat(chatInfo: .group(groupInfo: gInfo, groupChatScope: nil), chatItems: [])
            m.addChat(c)
            // Incognito has no member page at all; if nobody was picked, go to that page and choose there as before.
            if incognitoDefault || selectedContacts.isEmpty {
                withAnimation {
                    groupInfo = gInfo
                    chat = c
                }
                return
            }
            created = gInfo
        } catch {
            dismissAllSheets(animated: true) {
                AlertManager.shared.showAlert(
                    Alert(
                        title: Text(Copy.errorTitle),
                        message: Text(verbatim: responseError(error))
                    )
                )
            }
            return
        }
        await inviteSelectedMembers(created)
        finishCreating(created)
    }

    /// Copied word for word from `inviteMembers()` at AddGroupMembersView.swift:170-184: the same `apiAddMember`
    /// loop, the same `upsertGroupMember`, the same `showErrorAlert`. The group is opened even after the error dialog,
    /// for the reason written in item 5 of the file header.
    @MainActor private func inviteSelectedMembers(_ gInfo: GroupInfo) async {
        do {
            for contactId in selectedContacts {
                let member = try await apiAddMember(gInfo.groupId, contactId, selectedRole)
                await MainActor.run { _ = m.upsertGroupMember(gInfo, member) }
            }
        } catch let error {
            showErrorAlert(error, Copy.inviteErrorTitle)
        }
    }
}

