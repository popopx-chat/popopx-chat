/// If there is base64, draw the real image; if not, fall back to the brand mark — no placeholder person is drawn and the old theme is not borrowed for tinting.
private struct PopopxGroupAvatar: View {
    let imageStr: String?
    let side: CGFloat

    var body: some View {
        Group {
            if let uiImage = imageFromBase64(imageStr) {
                Image(uiImage: uiImage)
                    .resizable()
                    .interpolation(.high)
                    .scaledToFill()
                    .frame(width: side, height: side)
                    .clipShape(.rect(cornerRadius: PopopxMetrics.radiusAvatar, style: .continuous))
            } else {
                Image(PopopxBrandAsset.mark)
                    .resizable()
                    .interpolation(.high)
                    .scaledToFit()
                    .padding(PopopxMetrics.space2XS)
                    .frame(width: side, height: side)
                    .background(
                        PopopxPalette.separator,
                        in: .rect(cornerRadius: PopopxMetrics.radiusAvatar, style: .continuous)
                    )
            }
        }
        .frame(width: side, height: side)
        .overlay(
            RoundedRectangle(cornerRadius: PopopxMetrics.radiusAvatar, style: .continuous)
                .strokeBorder(PopopxPalette.hairlineInner, lineWidth: PopopxMetrics.hairline)
        )
        // The avatar is decoration on this screen: the name is on the very same chip, so VoiceOver is not asked to read it twice.
        .accessibilityHidden(true)
    }
}

