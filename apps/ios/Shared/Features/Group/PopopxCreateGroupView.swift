                    if canCreate { Task { await onSubmit() } }
                }
            )
            PopopxFormDivider()
            PopopxTextField(
                Copy.fullNameFieldLabel,
                prompt: Copy.fullNameFieldPrompt,
                text: $profile.fullName,
                systemImage: "textformat"
            )
            PopopxFormDivider()
