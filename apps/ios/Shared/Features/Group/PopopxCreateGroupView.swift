/// This screen only uses those four things, so on the page side `Contact` (POPOPXChat/ChatTypes.swift:2629) is projected into a
/// value type; previews can fill it with literals, with no live `ChatModel` and no network.
private struct PopopxInvitableContact: Identifiable, Hashable {
    let id: Int64
    let name: String
    let imageStr: String?
    /// The same "cannot be invited" judgement as that page; when true, tapping it asks a question instead of picking the person.
    let inviteProhibited: Bool
}

