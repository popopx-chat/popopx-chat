//
//  PopopxCameraGuardEngine.swift
//  POPOPX (iOS)
//
//  [top-secret alert · module three] front-camera watch for as long as the top-secret alert is up: one capture, three judgement paths.
//
//  This layer does only three things, and only during the few tens of seconds the top-secret alert is open:
//  1. opens the front camera at the lowest-power setting (`.vga640x480` + 10 FPS + single-frame callback, no writing to disk, no preview), and the moment the alert closes it
//     stops the stream and releases. The green dot in the top-right corner is the user's right to know as iOS gives it; "silent capture" does not exist on this system,
//     and the only thing that can be promised is "the camera lifecycle is strictly equal to the alert lifecycle".
//  2. runs synchronously inside the same frame: `VNDetectFaceRectanglesRequest` (headcount) + CoreML object detection (phone/camera)
//     + `PopopxGlareDetector` (lens glare). Only handing the first two requests to the same `VNImageRequestHandler.perform`
//     counts as parallel: Vision shares one copy of the image preprocessing, so running them apart decodes the same frame twice.
//  3. once it has judged, posts `PopopxSecurityAlert` back to the main thread. **It does not dispose of things itself**: locking the screen, destroying, sending the receipt
//     are all in `PopopxSecureWindowManager`; the engine only owns "what it saw".
//
//  ### A missing model is a normal state, not an error
//  `POPOPXAntiSpyDetector.mlmodelc` has to be generated by running `scripts/setup_pretrained_coreml.py` at the repo root by hand
//  (it writes to `apps/ios/Resources/SecureEphemeral/` by default), then dragged into the target by hand
//  (red line: the script may not touch `.pbxproj`). When it was not dragged in, `objectRequest` is nil,
//  and this engine automatically runs only the two "face + glare" paths, handing `startupNote` to the interface to display truthfully
//  ("object detection not enabled, only the glare-reflection fallback is at work") instead of pretending everything is fine.
//  The glare path is precisely the fallback prepared for this moment.
//
//  ### Three honest narrowings; do not advertise them outside as four capabilities
//  - **"the primary user left the view" ≠ recognising faces**. This SDK's `VNDetectFaceRectanglesRequest` has only the single property `results`
//    (no tunables of the `minFaceSize`/`accurateDetection` kind, checked against the iPhoneSimulator27.2 SDK
//    headers), and what it gives is boxes, not identities. Separating "the owner walked away" from "a different person is sitting there" needs a face-embedding
//    model, while the prompt's premise is "no manually trained models". So what this path judges is **`primaryViewerGrace` consecutive
//    seconds without a single face**; the copy says "the device owner left the view" and never claims to recognise who it was.
//  - **on the simulator this path cannot be tested at all**: the simulator has no front camera, `AVCaptureDevice.default(...)`
//    returns nil, so under `xcodebuild test` this file can only verify "refused to start, with a reason". A real device is the only source of evidence.
//  - **false positives are part of the design**: at 0.40 confidence a phone lying on the table or a black rectangle can both hit. So every
//    alert is **fuse-tripped on trigger + the user can switch the whole tier off**, and the interface copy only says what was detected, never "someone is photographing you".
//
//  ### Threading and teardown contract (where the prompt's "Lifecycle & Memory Leak Prevention" lands)
//  - `startMonitoring()` / `stopMonitoring()` may only be called on the main thread (`precondition` enforces it),
//    so "has it stopped" is answerable synchronously.
//  - the frame callback runs on the **serial** queue `com.popopx.vision.guard`; the pipeline object is touched only by this queue,
//    so inside the pipeline not a single lock is needed. What needs one is only the `sessionActive` flag that the main thread writes and the queue reads,
//    plus that one snapshot of `onAlert` taken at delivery time.
//  - the stop order is carved in stone: first set `sessionActive` to false (residual frames queued behind it see the flag and drop straight away),
//    then `setSampleBufferDelegate(nil)`, then `stopRunning()`, and finally let go of the session and pipeline references.
//    Written the other way round you get "the session has stopped but callbacks keep coming in", the hardest kind of crash to trace.
//
//  ⚠️ Xcode project integration: this file must be dragged into the POPOPX (iOS) target by hand. The red line forbids scripts from modifying project.pbxproj.
//

import AVFoundation
import CoreML
import CoreVideo
