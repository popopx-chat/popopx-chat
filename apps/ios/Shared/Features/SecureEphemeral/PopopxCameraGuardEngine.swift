// MARK: - Settings

/// The tiers the user is allowed to decide. A value type: `startMonitoring` snapshots it whole into the session,
/// and the session never reads external state again mid-flight - reading settings frame by frame inside the frame callback would bring cross-thread visibility problems for zero gain.
struct PopopxCameraGuardSettings: Hashable, Sendable {
    /// CoreML object detection (requires the model to have been imported). Off = only face + glare run.
    var objectDetectionEnabled = true
    /// the glare hot-spot fallback engine (pure CoreImage/Accelerate, zero package size).
    var glareDetectionEnabled = true
    /// Headcount watch. Off = no capture at all and this engine is left an empty shell (the green dot will not light either).
    var faceGuardEnabled = true
    /// Warn as soon as a second face appears.
    var alertOnSecondaryFace = true
    /// How many consecutive seconds without a single face counts as "the device owner left the view". 0.5 s is the number the prompt gave; any shorter starts
    /// judging "the user lowered their head to look at something" as a risk, and any longer loses the meaning.
    var primaryViewerGrace: TimeInterval = 0.5

    // The glare criteria thresholds (luma 245, area share, roundness 0.72) are **not here**: they live
    // in `PopopxGlareConfiguration.default`, and the interface offers no numeric adjustment either. Stuffing the whole config into this struct
    // would require that type to be `Hashable`, i.e. it would make this file's shape depend on another module's internal way of declaring things -
    // one less such coupling is one less seam that can go wrong silently.

    static let `default` = PopopxCameraGuardSettings()

    /// All three paths off = the camera should not be opened. `startMonitoring` computes this criterion itself rather than only trusting the caller.
    var requiresCameraAccess: Bool {
        faceGuardEnabled || glareDetectionEnabled || objectDetectionEnabled
    }
}

// MARK: - Startup result

/// Why the watch could not start. The interface must show this sentence, not "I tapped and nothing happened".
enum PopopxCameraGuardFailure: Error, Hashable, Sendable {
    /// The user has not decided yet (`.notDetermined`). This engine **does not raise the system permission prompt on its own**: at the moment the top-secret alert opens,
    /// popping a permission prompt is the same as interrupting the user at the very moment when he should least be interrupted. Permission is taken by the explicit button on the settings page
    /// (`PopopxCameraGuardEngine.requestCameraAccess`).
    case permissionNotDetermined
    /// Denied (`.denied`) or restricted (`.restricted`).
    case permissionDenied
    /// This device has no usable front camera (the simulator, or a very few models).
    case noFrontCamera
    /// The session could not be configured (another process holds the camera, or the device cannot be configured).
    case sessionUnavailable
    /// According to the settings no camera is needed in the first place.
    case notRequired

    var reasonText: String {
        switch self {
        case .permissionNotDetermined: return NSLocalizedString("The camera has not been authorised yet", comment: "")
        case .permissionDenied: return NSLocalizedString("Camera access is switched off; turn it on in the system settings", comment: "")
        case .noFrontCamera: return NSLocalizedString("This device has no front camera", comment: "")
        case .sessionUnavailable: return NSLocalizedString("Another app is using the camera right now", comment: "")
        case .notRequired: return NSLocalizedString("The guard is switched off in settings", comment: "")
        }
    }
}

// MARK: - Engine

/// Front-camera watch. Not an actor: public methods are contracted to the main thread, frame analysis all runs on the dedicated serial queue.
final class PopopxCameraGuardEngine {
    /// One detected event, one post. Deduplication and the fuse are done by the window manager; this layer caches nothing and retries nothing.
    /// **Called on the main thread only** (the pipeline has already done one hop).
    var onAlert: ((PopopxSecurityAlert) -> Void)?

    /// The settings used when starting according to settings/permission state. Read and written on the main thread.
    var settings: PopopxCameraGuardSettings = .default

    private let stateLock = NSLock()
    private var sessionActive = false
    private var session: PopopxCameraGuardSession?

    init() {}

    deinit {
        // The last fallback for a host that forgot to call `stopMonitoring()`. Put here instead of letting deinit only log:
        // an `AVCaptureSession` held by something outside the runloop keeps ticking until the process ends.
        session?.teardown()
    }

    var isMonitoring: Bool {
        stateLock.lock()
        defer { stateLock.unlock() }
        return sessionActive
    }

    /// The path that **failed to** run on the last startup, so the interface can state it truthfully. nil = every requested path is running.
    private(set) var startupNote: String?

    /// Object detection was enabled while the model was not imported - the interface uses this to decide whether to show "object detection not enabled" or nothing at all.
    var startedWithoutModel: Bool {
        stateLock.lock()
        let running = session
        stateLock.unlock()
        return running.map { !$0.hasObjectDetector } ?? false
    }

    /// Start the watch. Returning nil = success; returning a reason = it never started, and the interface shows `reasonText` directly.
    ///
    /// Idempotent: while already running, a second call does not create a second session (that would mean two captures fighting over one camera,
    /// and the first one would never be reachable again, so `stopRunning` could not be called at all).
    @discardableResult
    func startMonitoring() -> PopopxCameraGuardFailure? {
        precondition(Thread.isMainThread, "PopopxCameraGuardEngine.startMonitoring may only be called on the main thread")
        guard !isMonitoring else { return nil }
        let snapshot = settings
        guard snapshot.requiresCameraAccess else { return .notRequired }

        switch AVCaptureDevice.authorizationStatus(for: .video) {
        case .authorized: break
        case .notDetermined: return .permissionNotDetermined
        case .denied, .restricted: return .permissionDenied
        @unknown default: return .permissionDenied
        }

        let pipeline = PopopxGuardPipeline(settings: snapshot, deliver: { [weak self] alert in
            // frame queue -> main thread. `onAlert` can be set to nil on the main thread, so the snapshot is taken again once on the main thread,
            // rather than reading a cross-thread mutable reference on the queue.
            DispatchQueue.main.async {
                self?.stateLock.lock()
                let handler = self?.onAlert
                self?.stateLock.unlock()
                handler?(alert)
            }
        })
        let session: PopopxCameraGuardSession
        do {
            session = try PopopxCameraGuardSession(pipeline: pipeline, settings: snapshot)
        } catch let failure as PopopxCameraGuardFailure {
            return failure
        } catch {
            return .sessionUnavailable
        }

        stateLock.lock()
        sessionActive = true
        self.session = session
        stateLock.unlock()

        startupNote = pipeline.startupNote
        session.start()
        return nil
    }

    /// Stop the watch and release **deterministically**. See the file header for the order.
    func stopMonitoring() {
        precondition(Thread.isMainThread, "PopopxCameraGuardEngine.stopMonitoring may only be called on the main thread")
        stateLock.lock()
        sessionActive = false
        let closing = session
        session = nil
        stateLock.unlock()
        closing?.teardown()
        startupNote = nil
    }

    /// Ask for camera permission proactively. The opening flow of the top-secret alert does **not** call it (reason under `permissionNotDetermined`),
    /// the settings page has an explicit button that does; after authorisation the caller decides whether to restart the watch.
    static func requestCameraAccess(_ completed: @escaping (Bool) -> Void) {
        AVCaptureDevice.requestAccess(for: .video) { granted in
            DispatchQueue.main.async { completed(granted) }
        }
    }
}

// MARK: - Pipeline

/// All the judgement for one incoming frame. Not an actor, no locks: it lives only on that serial queue,
/// so every piece of mutable state is naturally single-threaded.
final class PopopxGuardPipeline: NSObject, AVCaptureVideoDataOutputSampleBufferDelegate {
    private let settings: PopopxCameraGuardSettings
    private let deliver: (PopopxSecurityAlert) -> Void

    private let faceRequest = VNDetectFaceRectanglesRequest()
    private let objectRequest: VNCoreMLRequest?
    private let glareDetector: PopopxGlareDetector?

    /// The startup note the interface wants to show. Computed at construction time and then unchanged, so it can sit on a `let` with no synchronisation.
    let startupNote: String?

    /// The last moment at which a face was still visible. nil = no frame has been received yet, and then leaving is never judged
    /// (otherwise the alert opens, the first frame has not arrived, and an alert is burned first).
    private var lastFaceSeenAt: Date?
    /// Whether this round of "no face visible" has already been reported. Once reported it stays silent until a face reappears -
    /// otherwise every frame after the owner walks away emits one, and the receipts would flood the session.
    private var primaryLossReported = false
    /// The last delivered event and its moment: the same kind of alert is not delivered twice inside the `repeatSuppression` window.
    private var lastReport: (alert: PopopxSecurityAlert, at: Date)?
    /// How long the last single-frame analysis took, used to decide whether this frame skips CoreML.
    private var lastAnalysisDuration: TimeInterval = 0
    private var skipObjectDetectionThisFrame = false

    /// Per-frame budget. At 10 FPS the frame interval is 100ms, but once capture callbacks queue up to frame 3 the picture already starts being dropped,
    /// so the budget is set at 60ms: over it and the next frame's CoreML is skipped, giving an effective object sampling rate of 5Hz.
    /// Better off with one object-detection path missing than letting the frame queue stretch past the closing of the alert - that is the real cause of "the green dot will not go out".
    private static let frameBudget: TimeInterval = 0.06

    /// The minimum interval between alerts of the same kind. The fuse itself trips only once; this guards against the 200ms before it,
    /// where the same event is reported once by each of two paths, producing two exactly identical receipts.
    private static let repeatSuppression: TimeInterval = 1.5

    /// See the file header for why only the face count at this level is taken: no boxes are drawn and no identity is judged, `boundingBox` is never used at all.
    private static let secondaryFaceCount = 2

    init(settings: PopopxCameraGuardSettings, deliver: @escaping (PopopxSecurityAlert) -> Void) {
        self.settings = settings
        self.deliver = deliver
        self.objectRequest = settings.objectDetectionEnabled ? PopopxGuardPipeline.makeObjectRequest() : nil
        self.glareDetector = settings.glareDetectionEnabled ? PopopxGlareDetector() : nil

        if !settings.objectDetectionEnabled {
            startupNote = NSLocalizedString("Object detection is switched off in settings.", comment: "")
        } else if objectRequest == nil {
            startupNote = NSLocalizedString("The POPOPXAntiSpyDetector model was not found, so object detection is off and only the glare reflection fallback is working.", comment: "")
        } else if settings.glareDetectionEnabled {
            startupNote = nil
        } else {
            startupNote = NSLocalizedString("The glare reflection fallback is switched off in settings.", comment: "")
        }
        super.init()
    }

    var hasObjectDetector: Bool { objectRequest != nil }

    // MARK: Frame callback

    func captureOutput(
        _ output: AVCaptureOutput,
        didOutput sampleBuffer: CMSampleBuffer,
        from connection: AVCaptureConnection
    ) {
        let beganAt = Date.now
        // `teardown()` first detaches this class from the output, so normally no frame comes in after the stream stops.
        // If one really does, it can only be from the batch before the detach: drop it outright, run no judgement and deliver no alert.
        guard CMSampleBufferGetNumSamples(sampleBuffer) >= 1 else { return }
        guard let pixelBuffer = CMSampleBufferGetImageBuffer(sampleBuffer) else { return }

        var requests: [VNRequest] = []
        if settings.faceGuardEnabled { requests.append(faceRequest) }
        if let objectRequest, !skipObjectDetectionThisFrame { requests.append(objectRequest) }

        if !requests.isEmpty {
            let handler = VNImageRequestHandler(cvPixelBuffer: pixelBuffer, orientation: Self.frameOrientation)
            do {
                try handler.perform(requests)
                if settings.faceGuardEnabled { evaluateFaces(at: beganAt) }
                if let objectRequest { evaluateObjects(objectRequest) }
            } catch {
                // an inference failure does not trip the fuse on a user message: that is the engine's problem, not a security event for the user.
                // but it cannot be treated as nothing either: push "the last time a face was seen" forward, otherwise repeated failures would be misjudged as the owner leaving,
                // and a single frame of inference error would become a view-once burn. The cost on this path is "the headcount is temporarily out of service", written here instead of hidden in a log.
                lastFaceSeenAt = beganAt
            }
        }

        if let glareDetector {
            switch glareDetector.process(pixelBuffer) {
            case .clear: break
            case .glare: report(.lensGlareDetected, when: beganAt)
            }
        }

        lastAnalysisDuration = Date.now.timeIntervalSince(beganAt)
        skipObjectDetectionThisFrame = lastAnalysisDuration > Self.frameBudget
    }

    // MARK: Judgement

    private func evaluateFaces(at now: Date) {
        let faces = (faceRequest.results ?? []).count
        if faces >= Self.secondaryFaceCount, settings.alertOnSecondaryFace {
            report(.secondaryFaceDetected, when: now)
        }
        guard settings.faceGuardEnabled else { return }
        if faces >= 1 {
            lastFaceSeenAt = now
            primaryLossReported = false
            return
        }
        guard let lastSeen = lastFaceSeenAt, !primaryLossReported else { return }
        guard now.timeIntervalSince(lastSeen) >= settings.primaryViewerGrace else { return }
        primaryLossReported = true
        report(.primaryViewerLost, when: now)
    }

    /// CoreML results can have two possible shapes, depending on whether the export went through `nms=True`:
    /// with an NMS head -> `VNRecognizedObjectObservation` (box + labels);
    /// a pure classification head -> `VNClassificationObservation`. Both branches are written because **the shape the script produces is not decided by this file**,
    /// and writing only one of them would silently become "the watch is on yet it never warns" under the other export mode.
    private func evaluateObjects(_ request: VNCoreMLRequest) {
        let observations = request.results ?? []
        var best: (object: PopopxGuardObject, confidence: Double)?

        func consider(label: String?, confidence: Double) {
            guard let label, let object = PopopxGuardObject.resolve(modelLabel: label) else { return }
            guard confidence >= object.threshold else { return }
            if best == nil || confidence > best!.confidence { best = (object, confidence) }
        }

        for observation in observations {
            if let detection = observation as? VNRecognizedObjectObservation {
                // take only `labels[].confidence`: in a model exported with `nms=True` this is the final score for that class.
                // do not multiply by `detection.confidence` - nothing in the documentation guarantees how those two numbers should be combined, and once you multiply them,
                // the 0.40/0.55 thresholds stop being a reproducible criterion and become a string of combinations nobody has verified.
                for label in detection.labels {
                    consider(label: label.identifier, confidence: Double(label.confidence))
                }
            } else if let classification = observation as? VNClassificationObservation {
                consider(label: classification.identifier, confidence: Double(classification.confidence))
            }
        }

        if let best { report(.recordingDevice(best.object), when: Date.now) }
    }

    private func report(_ alert: PopopxSecurityAlert, when now: Date) {
        if let last = lastReport, last.alert == alert, now.timeIntervalSince(last.at) < Self.repeatSuppression {
            return
        }
        lastReport = (alert, now)
        deliver(alert)
    }

    // MARK: Model

    /// Load the precompiled model; if it is missing or fails to load, return nil and the whole chain degrades. Reason in the file header.
    private static func makeObjectRequest() -> VNCoreMLRequest? {
        guard let url = compiledModelURL() else { return nil }
        let configuration = MLModelConfiguration()
        // `.cpuAndNeuralEngine`: only on the ANE is this 320x320 model down to single-digit milliseconds;
        // `.all` lets the system choose, and when it chooses the GPU the power draw pushes up against the thermal-throttling threshold for those tens of seconds of the alert.
        configuration.computeUnits = .cpuAndNeuralEngine
        guard let model = try? MLModel(contentsOf: url, configuration: configuration),
              let visionModel = try? VNCoreMLModel(for: model) else { return nil }
        let request = VNCoreMLRequest(model: visionModel)
        // the model is exported as a 320x320 square image and `.scaleFit` preserves the aspect ratio. We only use "is there a phone",
        // and never reconstruct `boundingBox`, so no error-prone inverse coordinate transform is needed here.
        request.imageCropAndScaleOption = .scaleFit
        return request
    }

    /// Only `mlmodelc` is accepted: `.mlpackage` is the **source**, and Xcode must compile it into the app at build time before `MLModel` can read it.
    /// A bare `.mlpackage` lying in the bundle equals no model at all, and at runtime there is no Xcode toolchain to compile it on the spot.
    /// If it is not found, return nil and let the degradation path + `startupNote` say it clearly.
    private static func compiledModelURL() -> URL? {
        if let url = Bundle.main.url(forResource: modelName, withExtension: "mlmodelc") {
            return url
        }
        // If the script's output directory was copied into the bundle whole as a folder reference, the model is inside that layer.
        // Both are tried, because both integration styles are legitimate and which one applies is decided when the file is dragged in by hand.
        return Bundle.main.url(forResource: modelName, withExtension: "mlmodelc", subdirectory: modelSubdirectory)
    }

    private static let modelName = "POPOPXAntiSpyDetector"
    private static let modelSubdirectory = "SecureEphemeral"

    /// The orientation of the buffers the front camera delivers while the phone is held portrait. The only place it is used here is "let Vision turn the face
    /// boxes upright", and the judgement looks only at **how many boxes there are**, so the worst consequence of a value one step off is a missed frame, not a coordinate offset.
    /// `connection.videoOrientation` is not set (deprecated since iOS 17, replaced by `videoRotationAngle`
    /// which only affects the preview transform), and no device-attitude tracking is done either: the top-secret alert is portrait itself.
    private static let frameOrientation = CGImagePropertyOrientation.right
}

// MARK: - Session

/// The lifecycle object of one capture session. After `teardown()` it no longer holds any system resource.
final class PopopxCameraGuardSession {
    private let captureSession = AVCaptureSession()
    private let pipeline: PopopxGuardPipeline
    private let videoQueue: DispatchQueue
    private var input: AVCaptureDeviceInput?
    private var output: AVCaptureVideoDataOutput?
    private var tornDown = false

    var hasObjectDetector: Bool { pipeline.hasObjectDetector }

    init(pipeline: PopopxGuardPipeline, settings: PopopxCameraGuardSettings) throws {
        self.pipeline = pipeline
        // The queue name is this feature's only identity inside Console.app; do not change it.
        self.videoQueue = DispatchQueue(
            label: "com.popopx.vision.guard",
            qos: .userInitiated,
            attributes: [],
            autoreleaseFrequency: .workItem
        )
        guard settings.requiresCameraAccess else { throw PopopxCameraGuardFailure.notRequired }
        guard let device = AVCaptureDevice.default(.builtInWideAngleCamera, for: .video, position: .front)
        else { throw PopopxCameraGuardFailure.noFrontCamera }

        captureSession.beginConfiguration()
        // `.vga640x480`: the tier the prompt specifies, and also the smallest usable tier on this camera.
        // If it is unsupported, do not set a preset (rather than throwing): a preset is "how big a picture",
        // while "whether the watch should run" depends only on whether frames can be obtained.
        if captureSession.canSetSessionPreset(.vga640x480) {
            captureSession.sessionPreset = .vga640x480
        }

        do {
            try Self.applyPowerSavingFrameRate(to: device)
        } catch {
            captureSession.commitConfiguration()
            throw PopopxCameraGuardFailure.sessionUnavailable
        }

        // `AVCaptureDeviceInput(device:)` is throwing rather than failable (writing the first version with `guard let` would be
        // rejected by the compiler on the spot), so a try is mandatory here; every failure reason is folded into "the session could not be configured".
        let input: AVCaptureDeviceInput
        do {
            input = try AVCaptureDeviceInput(device: device)
        } catch {
            captureSession.commitConfiguration()
            throw PopopxCameraGuardFailure.sessionUnavailable
        }
        guard captureSession.canAddInput(input) else {
            captureSession.commitConfiguration()
            throw PopopxCameraGuardFailure.sessionUnavailable
        }
        captureSession.addInput(input)

        let output = AVCaptureVideoDataOutput()
        // Late frames are dropped outright: what the watch needs is "is there a second face right now", and queued old frames only give an expired answer,
        // and they would push the post-stop callbacks past the closing of the alert.
        output.alwaysDiscardsLateVideoFrames = true
        // **It must be FullRange**: `PopopxGlareDetector`'s threshold is `Luma > 245`,
        // while VideoRange caps luma at 235 - getting this line wrong raises no error and crashes nothing,
        // it only makes the entire glare path never trigger. The difference between the two formats is written in this line's comment.
        output.videoSettings = [
            kCVPixelBufferPixelFormatTypeKey as String: Int(kCVPixelFormatType_420YpCbCr8BiPlanarFullRange)
        ]
        output.setSampleBufferDelegate(pipeline, queue: videoQueue)
        guard captureSession.canAddOutput(output) else {
            output.setSampleBufferDelegate(nil, queue: nil)
            captureSession.commitConfiguration()
            throw PopopxCameraGuardFailure.sessionUnavailable
        }
        captureSession.addOutput(output)

        Self.applyAutoFocus(to: device)

        self.input = input
        self.output = output
        captureSession.commitConfiguration()
    }

    deinit {
        #if DEBUG
        // Reclamation assertion: when ARC releases the session the stream must already be stopped. Still running = someone missed `stopMonitoring()`,
        // and on a real device that shows up as "the top-secret alert closed long ago, the camera green dot is still lit".
        precondition(!captureSession.isRunning, "PopopxCameraGuardSession is released while the capture stream is still running: stopMonitoring() was never called")
        #endif
        // deinit only does the clean-up that needs no main-thread guarantee; the `precondition(Thread.isMainThread)`-carrying
        // `teardown()` may only be called by `stopMonitoring()`, and we do not decide which thread ARC lands on.
        output?.setSampleBufferDelegate(nil, queue: nil)
        if captureSession.isRunning { captureSession.stopRunning() }
    }

    func start() {
        // Blocks the calling thread synchronously for some tens of milliseconds. Not being async is deliberate: `isMonitoring` must be true at the same instant as the green dot,
        // otherwise the alert is already on screen while the watch has not started, and that stretch in between is a real "unguarded window".
        captureSession.startRunning()
    }

    /// The order is carved in stone, see `stopMonitoring()`. Idempotent: repeated calls do it only once.
    func teardown() {
        guard !tornDown else { return }
        tornDown = true
        output?.setSampleBufferDelegate(nil, queue: nil)
        if captureSession.isRunning { captureSession.stopRunning() }
        captureSession.beginConfiguration()
        if let input { captureSession.removeInput(input) }
        if let output { captureSession.removeOutput(output) }
        captureSession.commitConfiguration()
        self.input = nil
        self.output = nil
    }

    /// Target frame rate. 10 FPS is the tier the prompt gave, and also the physical floor for "a second head leaning in":
    /// at 10 FPS a person moving from outside the picture into it takes roughly 3~4 frames, enough to judge; anything more only burns power for nothing and produces heat.
    private static let targetFramesPerSecond: Float64 = 10

    /// Pins the frame rate at 10 FPS.
    ///
    /// **Resolution is not managed here**: it is decided by the `.vga640x480` preset, which is exactly the entry point Apple gives for choosing resolution.
    /// Setting `activeFormat` by hand looks more power-efficient, but `activeFormat` carries one rule that can only be verified on a real device: the format must be supported
    /// by the current preset, otherwise it throws `NSInvalidArgumentException` (an ObjC exception that Swift's `catch` cannot catch,
    /// so it shows up as "opening the top-secret alert crashes"). And the simulator has no front camera, so this crash path cannot be reached by any
    /// automation in this project. That is why only one thing that can be made certain is kept here: the frame rate.
    ///
    /// When the current `activeFormat` does not support 10 FPS, **only the frame-rate setting is skipped**; the watch is not abandoned: a slightly higher frame rate only means more power,
    /// whereas "no watch at all because no format could be picked" turns a safety check into a silent failure, exactly the class of bug this file keeps guarding against.
    private static func applyPowerSavingFrameRate(to device: AVCaptureDevice) throws {
        try device.lockForConfiguration()
        defer { device.unlockForConfiguration() }
        guard supportsTargetFrameRate(in: device.activeFormat) else { return }
        let duration = CMTime(value: 1, timescale: CMTimeScale(targetFramesPerSecond))
        device.activeVideoMinFrameDuration = duration
        device.activeVideoMaxFrameDuration = duration
    }

    /// The frame-rate range must cover 10 at **both ends**: `minFrameDuration <= 0.1s <= maxFrameDuration`.
    /// Checking only one end is the common mistake - that would judge a format which tops out at 5FPS as usable,
    /// and then setting `activeVideoMinFrameDuration` takes no effect (or throws an exception).
    private static func supportsTargetFrameRate(in format: AVCaptureDevice.Format) -> Bool {
        format.videoSupportedFrameRateRanges.contains { range in
            range.minFrameDuration.seconds <= 1.0 / targetFramesPerSecond
                && range.maxFrameDuration.seconds >= 1.0 / targetFramesPerSecond
        }
    }

    /// Autofocus. Skipped if unsupported: the watch needs no sharp picture, only a countable "how many bright spots, how many faces".
    /// The reason it is written into the code: it belongs to the kind of setting where "delete it and it still runs, only the criteria get worse",
    /// and whoever reads this next needs to know it was deliberate.
    ///
    /// `lockForConfiguration()` must have its errors genuinely checked here: calling `unlock` without holding the lock throws an ObjC exception,
    /// so `try?` plus an unconditional `unlock` is a pattern that looks harmless and in fact turns a momentary permission hiccup into a crash.
    private static func applyAutoFocus(to device: AVCaptureDevice) {
        guard device.isFocusModeSupported(.continuousAutoFocus) else { return }
        guard (try? device.lockForConfiguration()) != nil else { return }
        device.focusMode = .continuousAutoFocus
        device.unlockForConfiguration()
    }
}
